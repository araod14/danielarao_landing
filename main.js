form.addEventListener('submit', async (event) => {
  event.preventDefault();
  if (submitting) return;
  const fields = new FormData(form);
  const payload = Object.fromEntries(['name', 'email', 'message'].map((key) => [key, String(fields.get(key)).trim()]));
  if (!form.checkValidity() || payload.name.length < 2 || payload.message.length < 10) {
    formState = 'invalid';
    renderStatus();
    const invalidField = form.querySelector(':invalid');
    (invalidField || status).focus({ preventScroll: true });
    return;
  }
  submitting = true;
  submitButton.disabled = true;
  formState = 'sending';
  renderStatus();
  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), 20000);
  try {
    const response = await fetch('/api/contact', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Accept': 'application/json' },
      body: JSON.stringify(payload),
      signal: controller.signal
    });
    if (response.status === 429) {
      formState = 'limited';
    } else if (response.status === 422 || response.status === 400) {
      formState = 'invalid';
    } else if (response.ok) {
      const result = await response.json();
      if (result.status !== 'sent') throw new Error('Unconfirmed delivery');
      formState = 'sent';
      form.reset();
    } else {
      formState = 'unavailable';
    }
  } catch {
    formState = 'unavailable';
  } finally {
    clearTimeout(timeout);
    submitting = false;
    submitButton.disabled = false;
    renderStatus();
    status.focus({ preventScroll: true });
  }
});
